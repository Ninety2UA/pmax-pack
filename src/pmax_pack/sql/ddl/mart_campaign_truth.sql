  CAST(NULL AS INT64) AS account_id,
  CAST(NULL AS INT64) AS campaign_id,
  CAST(NULL AS STRING) AS campaign_name,
  CAST(NULL AS STRING) AS campaign_status,
  CAST(NULL AS STRING) AS ad_network_type,
